    //正常
    public static void register(String machineId, BlockPos... positions) {
        ResourceLocation id = ResourceLocation.parse(machineId);
        HATCH_SLOTS.computeIfAbsent(id, k -> new ArrayList<>()).addAll(List.of(positions));
    }

    //翻转
    public static void registerFlipped(String machineId, BlockPos... positions) {
        ResourceLocation id = ResourceLocation.parse(machineId);
        List<BlockPos> list = HATCH_SLOTS.computeIfAbsent(id, k -> new ArrayList<>());

        for (BlockPos pos : positions) {
            // 自动翻转 X 和 Z
            list.add(new BlockPos(-pos.getX(), pos.getY(), -pos.getZ()));
        }
    }

    public static void registerArea(String machineId, BlockPos pos1, BlockPos pos2) {
        int minX = Math.min(pos1.getX(), pos2.getX());
        int minY = Math.min(pos1.getY(), pos2.getY());
        int minZ = Math.min(pos1.getZ(), pos2.getZ());

        int maxX = Math.max(pos1.getX(), pos2.getX());
        int maxY = Math.max(pos1.getY(), pos2.getY());
        int maxZ = Math.max(pos1.getZ(), pos2.getZ());

        for (int x = minX; x <= maxX; x++) {
            for (int y = minY; y <= maxY; y++) {
                for (int z = minZ; z <= maxZ; z++) {
                    register(machineId, new BlockPos(x, y, z));
                }
            }
        }
    }

    public static List<BlockPos> getPositions(ResourceLocation machineId) {
        return HATCH_SLOTS.getOrDefault(machineId, List.of());
    }
